/* ── Running Particle Canvas Background ──────────────────────── */
function initBackgroundParticles() {
    const canvas = document.getElementById('particle-canvas');
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    let width = canvas.width = window.innerWidth;
    let height = canvas.height = window.innerHeight;

    window.addEventListener('resize', () => {
        width = canvas.width = window.innerWidth;
        height = canvas.height = window.innerHeight;
    });

    const particles = [];
    const particleCount = Math.min(Math.floor((width * height) / 18000), 55);

    for (let i = 0; i < particleCount; i++) {
        particles.push({
            x: Math.random() * width,
            y: Math.random() * height,
            radius: Math.random() * 2 + 1,
            vx: (Math.random() - 0.5) * 0.45,
            vy: (Math.random() - 0.5) * 0.45,
            alpha: Math.random() * 0.5 + 0.2,
            hue: Math.random() > 0.5 ? 270 : 320
        });
    }

    function animate() {
        ctx.clearRect(0, 0, width, height);

        for (let i = 0; i < particles.length; i++) {
            const p = particles[i];
            p.x += p.vx;
            p.y += p.vy;

            if (p.x < 0) p.x = width;
            if (p.x > width) p.x = 0;
            if (p.y < 0) p.y = height;
            if (p.y > height) p.y = 0;

            ctx.beginPath();
            ctx.arc(p.x, p.y, p.radius, 0, Math.PI * 2);
            ctx.fillStyle = `hsla(${p.hue}, 80%, 70%, ${p.alpha})`;
            ctx.shadowBlur = 10;
            ctx.shadowColor = `hsla(${p.hue}, 80%, 70%, 0.8)`;
            ctx.fill();

            for (let j = i + 1; j < particles.length; j++) {
                const p2 = particles[j];
                const dx = p.x - p2.x;
                const dy = p.y - p2.y;
                const dist = Math.sqrt(dx * dx + dy * dy);

                if (dist < 110) {
                    ctx.beginPath();
                    ctx.moveTo(p.x, p.y);
                    ctx.lineTo(p2.x, p2.y);
                    ctx.strokeStyle = `hsla(${p.hue}, 70%, 65%, ${0.14 * (1 - dist / 110)})`;
                    ctx.lineWidth = 0.75;
                    ctx.stroke();
                }
            }
        }
        requestAnimationFrame(animate);
    }
    animate();
}

/* ── Visual Effect Helpers ─────────────────────────────────────── */
function createParticles(originEl, color, count = 24) {
    const rect = originEl.getBoundingClientRect();
    const cx = rect.left + rect.width  / 2;
    const cy = rect.top  + rect.height / 2;
    for (let i = 0; i < count; i++) {
        const p = document.createElement('div');
        p.className = 'particle';
        const angle = (Math.PI * 2 * i) / count + Math.random() * 0.4;
        const dist  = 65 + Math.random() * 160;
        const size  = 5  + Math.random() * 12;
        Object.assign(p.style, {
            left:      cx + 'px',
            top:       cy + 'px',
            width:     size + 'px',
            height:    size + 'px',
            background: color,
            boxShadow: `0 0 ${size * 1.5}px ${color}`,
        });
        p.style.setProperty('--dx',  Math.cos(angle) * dist + 'px');
        p.style.setProperty('--dy',  Math.sin(angle) * dist + 'px');
        p.style.setProperty('--dur', (0.7 + Math.random() * 0.5) + 's');
        document.body.appendChild(p);
        setTimeout(() => p.remove(), 1300);
    }
}

