    // Background Gradient
    const bgGrad = ctx.createLinearGradient(0, 0, width, height);
    bgGrad.addColorStop(0, '#0d0322');
    bgGrad.addColorStop(0.5, '#180738');
    bgGrad.addColorStop(1, '#07000f');
    ctx.fillStyle = bgGrad;
    ctx.fillRect(0, 0, width, height);

